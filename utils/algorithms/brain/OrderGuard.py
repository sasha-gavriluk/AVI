import time

from utils.OtherUtils import _handle_error

#==============================
# Правило скасування ордера
#==============================
#
# Між рішенням і виконанням минає час: підготовка свічки, дорога до біржі,
# сама постановка ордера. Заміряно 01.09.2026 — близько 4 секунд у типовому
# випадку. Це коштує дрібниць: крива чутливості показала, що перевага
# тримається аж до півтори хвилини запізнення й помирає десь на п'яти.
#
# Але «типово» не означає «завжди». Мережа підвисне, біржа відповість не
# одразу — і ми зайдемо за ціною, якої вже немає.
#
# Тому правило: не встигли швидко — не заходимо взагалі. Так невизначений
# ризик поганої ціни перетворюється на визначений ризик пропущеної угоди.
# Друге завжди дешевше.
#
# ДВІ УМОВИ, і друга важливіша. Час — це посередник, а болить рух ціни:
# двадцять секунд у штиль коштують нуль, а двадцять секунд на новинах —
# відсоток. Тому головна умова саме по ціні, а час страхує на випадок,
# коли ціну взагалі не вдається отримати.
#==============================


class OrderGuard:
    "Вирішує, чи ще актуальний ордер, чи його пора скасувати"

    #------------------------------
    # Constants (Можна змінювати)
    #------------------------------

    # Скільки секунд від ЗАКРИТТЯ СВІЧКИ ордер ще вважається свіжим.
    # За домовленістю 02.09.2026 — 30 секунд (було 20).
    #
    # Відлік іде від закриття свічки, а не від моменту, коли ми зібрались
    # надсилати ордер. Інакше вимір показував би час самої відправки й
    # не бачив би найдовшої частини — збірки фічей.
    MAX_DELAY_SEC = 30.0

    # Наскільки ціна може відійти від тієї, на якій ухвалювалось рішення.
    # 0.05% це приблизно третина типового руху за п'ять хвилин і вдвічі
    # більше за очікуване ковзання на чотирьох секундах.
    MAX_SLIP_PCT = 0.05

    #------------------------------
    # Ініціалізація класу
    #------------------------------

    def __init__(self, max_delay_sec: float = None, max_slip_pct: float = None):
        self.max_delay_sec = max_delay_sec if max_delay_sec is not None else self.MAX_DELAY_SEC
        self.max_slip_pct = max_slip_pct if max_slip_pct is not None else self.MAX_SLIP_PCT

    #------------------------------
    # Створення наміру
    #------------------------------

    @_handle_error
    def intent(self, decision_price: float, direction: str,
               started: float = None) -> dict:
        """
        Фіксує момент, від якого міряється запізнення.

        :param started: мітка time.monotonic() ЗАКРИТТЯ СВІЧКИ. None — зараз.
                        Живий цикл передає її обов'язково: бюджет у 30 секунд
                        відлічується від свічки, а не від початку нашої роботи
        :return: намір, який треба показати методу check() перед відправкою
        """
        return {
            'decision_price': float(decision_price),
            'direction': direction,
            'created': time.monotonic() if started is None else float(started),
        }

    #------------------------------
    # Перевірка перед відправкою
    #------------------------------

    @_handle_error
    def check(self, intent: dict, price_now: float) -> dict:
        """
        Чи ще можна виставляти ордер.

        :return: {'allowed': bool, 'reason': str, 'delay_sec': float, 'slip_pct': float}
        """
        delay = time.monotonic() - intent['created']
        base = intent['decision_price']
        drift = (price_now - base) / base * 100.0 if base else 0.0

        # Рух ПРОТИ нас шкодить, рух за нас — ні. Для купівлі шкідливе
        # зростання ціни, для продажу — падіння.
        against = drift if intent['direction'] == 'BUY' else -drift

        answer = {'delay_sec': round(delay, 2), 'slip_pct': round(against, 4)}

        if delay > self.max_delay_sec:
            return {**answer, 'allowed': False,
                    'reason': f'Запізнення {delay:.1f} с (межа {self.max_delay_sec:.0f} с)'}

        if against > self.max_slip_pct:
            return {**answer, 'allowed': False,
                    'reason': (f'Ціна відійшла на {against:.3f}% проти нас '
                               f'(межа {self.max_slip_pct:.2f}%)')}

        return {**answer, 'allowed': True, 'reason': ''}
