# ЗМІНА (30.08.2026) — FeatureAttention гасила весь вхід у 113 разів
#
# БУЛО (оригінал, FeatureAttention.forward):
#     weights = torch.softmax(self.feature_weights, dim=0)
#     return x * weights, weights
#
# СТАЛО:
#     scale = weights * weights.numel()
#     return x * scale, weights
#
# ЧОМУ (причина, заміряна 30.08 перевірками 10 і 11):
# softmax за означенням дає суму 1. При 113 фічах кожна отримувала вагу близько
# 1/113 = 0.0088, тобто ВЕСЬ вхід множився на 0.0088. Заміряно по кроках encode():
#     вхід                     розкид між вікнами 0.306
#     після уваги до фічей     0.0027   <- падіння у 111 разів
#     після проекції           0.0448   (позиційна складова при цьому 0.631 і однакова)
#     після трансформера       0.0021
#     після другої уваги       0.00027
#     вектор стану h_last      0.000001 <- вікна стали НЕВІДРІЗНЯННІ
# Косинусна схожість векторів стану різних вікон дорівнювала 1.000000, а ймовірність
# BUY була та сама до шостого знака (0.499965) для всіх вікон.
#
# Тобто мережа фізично не бачила різниці між вікнами: у трансформер заходила майже
# чиста позиційна підкладка, однакова для всіх, а дані складали ~7% вмісту й
# стиралися усередненням по тисячі позицій.
#
# Це пояснює головну загадку: чому CE стояв рівно на ln 2 = 0.6931 у ВСІХ прогонах,
# чому голови злипались у сталі відповіді й чому впевненість мала розкид 0.6 п.п.
# Мережа не «не могла навчитись» — їй не було на що дивитись.
#
# Множення на кількість фічей робить середню вагу одиницею замість 1/113. Відносна
# важливість фічей зберігається повністю, а назовні й далі віддаються самі softmax-ваги,
# щоб звіт «Аналіз Важливості Фічей» читався у відсотках, як і раніше.
#
# Оригінал файлу перед правкою: scratchpad/model.py.bak_20260830.
# ==========================================================================================
