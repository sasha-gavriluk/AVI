# ArchitectureNN.py
# Сама нейромережа ChronoSeer. Дивиться на вікно свічок і видає рішення
# по кожному горизонту.
#
# Перенесено 01.09.2026 з AI_Lab/Futures/Transformer/model.py разом із
# перейменуванням класу HybridMarketModel -> ChronoSeer.

import math
import torch
import torch.nn as nn
import torch.nn.functional as F

# Горизонти за замовчуванням. Раніше вони тягнулись із датасету лабораторії,
# але Code не має залежати від AI_Lab — залежність іде тільки в один бік.
# Усі, хто створює мережу, і так передають horizons явно, бо їх кількість
# зашита у ваги: скільки горизонтів, стільки комплектів голів.
DEFAULT_HORIZONS = [15, 30, 50]


# ===========================
# PositionalEncoding - додає до кожної свічки позначку «яка ти по порядку».
#
# Навіщо: трансформер сам по собі НЕ бачить порядку. Для нього вікно свічок —
# це купа, а не послідовність. Перемішай свічки місцями — він не помітить.
# А для ринку порядок і є найголовніше.
#
# Як: до кожної свічки додається набір синусів і косинусів різної довжини хвилі.
# Виходить щось на кшталт відбитка пальця позиції: у свічки №5 він один,
# у свічки №900 інший, і мережа за ним відрізняє «давно» від «щойно».
# ===========================

class PositionalEncoding(nn.Module):

    #------------------------------
    # init
    #------------------------------

    def __init__(self, d_model: int, max_len: int = 1000):
        """
        :param d_model: розмір внутрішнього вектора мережі
        :param max_len: максимальна довжина вікна, яку треба вміти позначити
        """
        super().__init__()

        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model))

        # Парні числа вектора — синус, непарні — косинус. Разом дають унікальний
        # візерунок на кожну позицію.
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)

        # register_buffer = «зберігати разом із вагами, але НЕ навчати».
        # Ці числа фіксовані, вони не підбираються під дані.
        self.register_buffer('pe', pe.unsqueeze(0))

    #------------------------------
    # forward
    #------------------------------

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        "Просто додає позначку позиції до кожної свічки вікна"
        return x + self.pe[:, :x.size(1)]


# ===========================
# FeatureAttention - вирішує, на які фічі взагалі варто дивитись.
#
# У нас 113 колонок на кожну свічку. Частина з них корисна, частина — шум.
# Замість того щоб вирішувати це руками, мережа сама вчить вагу кожної колонки.
#
# Ваги проганяються через softmax, тобто сумуються в одиницю — виходить чесний
# розподіл уваги. Побачити його можна в логах навчання: рядок «Аналіз Важливості
# Фічей». Саме так ми і з'ясували, що 5m-колонки майже не потрібні.
# ===========================

class FeatureAttention(nn.Module):

    #------------------------------
    # init
    #------------------------------

    def __init__(self, input_dim: int):
        """
        :param input_dim: скільки всього фічей на одну свічку
        """
        super().__init__()
        # nn.Parameter = число, яке мережа підбирає сама під час навчання.
        # Стартуємо з одиниць, тобто «спершу всі фічі однаково важливі».
        self.feature_weights = nn.Parameter(torch.ones(input_dim))

    #------------------------------
    # forward
    #------------------------------

    def forward(self, x: torch.Tensor):
        """
        :param x: [Батч, Свічки, Фічі]
        :return: (зважені дані, самі ваги — щоб можна було подивитись)
        """
        weights = torch.softmax(self.feature_weights, dim=0)

        # Множимо на кількість фічей, щоб СЕРЕДНЯ вага дорівнювала одиниці.
        # Без цього softmax (сума якого завжди 1) ділив увесь вхід на 113 —
        # і дані переставали бути видимими на тлі позиційних позначок.
        # Відносна важливість фічей при цьому не змінюється: удвічі важливіша
        # фіча так і лишається вдвічі важливішою.
        scale = weights * weights.numel()

        # Множення розходиться по всіх свічках батча: кожна колонка отримує свою вагу.
        # Назовні віддаємо самі softmax-ваги — у звіті вони читаються як відсотки.
        return x * scale, weights


# ===========================
# ChronoSeer - головна мережа. Перенесено з AI_Lab/Futures/Transformer/model.py
# 01.09.2026 разом із перейменуванням із HybridMarketModel. Три погляди на ті самі дані підряд:
#
# 1. ТРАНСФОРМЕР — глобальний контекст. Дивиться на все вікно одразу й сам
#    вирішує, які свічки з якими пов'язані. Може зв'язати свічку №3 зі свічкою
#    №870, якщо вважає це важливим.
#
# 2. ЗГОРТКА (Conv1d) — локальні сусідства. Дивиться на кожні три свічки поспіль
#    і шукає короткі візерунки: сплеск, злам, три однакові свічки. Те, що
#    трансформер може розмазати, бо він дивиться широко.
#
# 3. УВАГА (MultiheadAttention) — ще один прохід порівняння вже оброблених
#    ділянок між собою, після того як згортка виділила локальні риси.
#
# Після кожного з двох останніх блоків стоїть ЗАЛИШКОВИЙ ЗВ'ЯЗОК (x + результат)
# і нормалізація. Без них кожен блок повністю затирав би те, що напрацював
# попередній, і глибші шари вчились би гірше — градієнту нема як пройти назад.
# У самому TransformerEncoderLayer таке вже вбудовано, а от у Conv1d і MHA — ні,
# тому їх треба обгортати руками.
#
# ACT (адаптивні прокрутки роздумів) прибрано свідомо: замір показав, що механізм
# ніколи не адаптувався — або впирався в максимум 6, або сидів на 1.00.
# ===========================

class ChronoSeer(nn.Module):

    #------------------------------
    # init
    #------------------------------

    def __init__(self, input_dim: int, d_model: int = 256, nhead: int = 8,
                 num_classes: int = 3, dropout: float = 0.1, horizons: list = None):
        """
        :param input_dim: скільки фічей на свічку (зараз 113)
        :param d_model: розмір внутрішнього вектора — «обсяг робочої пам'яті» мережі
        :param nhead: скільки паралельних поглядів на дані всередині уваги
        :param num_classes: 3 — WAIT / BUY / SELL
        :param dropout: яку частку зв'язків випадково глушити під час навчання.
                        Захист від запам'ятовування: мережа не може покластись на
                        якийсь один шлях, бо його щоразу можуть вимкнути.
        :param horizons: список горизонтів; на кожен буде свій комплект голів
        """
        super().__init__()

        self.d_model = d_model
        self.horizons = list(horizons) if horizons is not None else list(DEFAULT_HORIZONS)

        # 0. Ваги важливості фічей
        self.feature_attention = FeatureAttention(input_dim)

        # 1. Вхідна проекція: перетворює 113 фічей у внутрішній вектор.
        # Це як переклад із «мови даних» на внутрішню мову мережі.
        self.input_projection = nn.Linear(input_dim, d_model)
        self.pos_encoder = PositionalEncoding(d_model=d_model)
        self.dropout1 = nn.Dropout(dropout)

        # 2. Трансформер — глобальний контекст
        self.transformer_layer = nn.TransformerEncoderLayer(
            d_model=d_model,
            nhead=nhead,
            dim_feedforward=d_model * 2,
            dropout=dropout,
            batch_first=True    # дані приходять як [Батч, Свічки, Фічі]
        )

        # 3. Згортка — локальні сусідства.
        # kernel_size=3 означає «дивись на три свічки поспіль»,
        # padding=1 зберігає довжину вікна: скільки свічок зайшло, стільки й вийде.
        self.conv1d = nn.Conv1d(in_channels=d_model, out_channels=d_model,
                                kernel_size=3, padding=1)
        self.norm_conv = nn.LayerNorm(d_model)
        self.dropout2 = nn.Dropout(dropout)

        # 4. Ще один прохід уваги — уже по оброблених ділянках
        self.mha = nn.MultiheadAttention(embed_dim=d_model, num_heads=nhead,
                                         dropout=dropout, batch_first=True)
        self.norm_mha = nn.LayerNorm(d_model)

        # 5. Фінальне стиснення. Розмір лишається d_model, щоб нічого не було
        # зашито числом: поміняєш d_model — усе підхопиться саме.
        self.fc = nn.Linear(d_model, d_model)
        self.gelu = nn.GELU()

        # 6. Голови прогнозу — по комплекту на кожен горизонт.
        # Кожна голова це просто nn.Linear: бере вектор стану й перетворює
        # його на потрібну відповідь.
        # Вхід голів = стан мережі (d_model) + стан рахунку (5 чисел).
        head_in = d_model + 5
        self.direction_heads = nn.ModuleList([nn.Linear(head_in, num_classes) for _ in self.horizons])
        self.tp_heads = nn.ModuleList([nn.Linear(head_in, 1) for _ in self.horizons])  # Тейк-Профіт, п.п.
        self.sl_heads = nn.ModuleList([nn.Linear(head_in, 1) for _ in self.horizons])  # Стоп-Лос, п.п.

        # Голова оцінки стану — залишок від РЛ-етапу. Рахується, але у втрати
        # не входить, тобто зараз ні на що не впливає.
        self.value_head = nn.Linear(head_in, 1)

    #------------------------------
    # Читання вікна: три погляди підряд
    #------------------------------

    def encode(self, x: torch.Tensor):
        """
        Проганяє вікно свічок через усі три блоки й повертає вектор свічки рішення.

        :param x: [Батч, Свічки, Фічі]
        :return: (вектор останньої свічки, ваги фічей)
        """
        # 0. Приглушуємо непотрібні фічі
        x, feature_weights = self.feature_attention(x)

        # 1. Переводимо у внутрішню мову й додаємо позначки позицій.
        # Множення на корінь із d_model — стандартний прийом, щоб числа після
        # проекції були співмірні з позиційними позначками.
        x = self.input_projection(x) * math.sqrt(self.d_model)
        x = self.pos_encoder(x)
        x = self.dropout1(x)

        # 2. Глобальний контекст (усередині вже є залишковий зв'язок і нормалізація)
        x = self.transformer_layer(x)

        # 3. Згортка. Вона хоче дані у вигляді [Батч, Ознаки, Свічки], а
        # трансформер віддає [Батч, Свічки, Ознаки] — тому два permute навколо.
        conv_out = x.permute(0, 2, 1)
        conv_out = self.conv1d(conv_out)
        conv_out = conv_out.permute(0, 2, 1)

        # Залишковий зв'язок: ДОДАЄМО результат до входу, а не заміняємо ним.
        # Так мережа може використати згортку як уточнення, а не як заміну.
        x = self.norm_conv(x + self.dropout2(conv_out))

        # 4. Другий прохід уваги. mha повертає (результат, ваги уваги) — беремо [0].
        mha_out, _ = self.mha(query=x, key=x, value=x, need_weights=False)
        x = self.norm_mha(x + mha_out)

        # 5. Беремо вектор ОСТАННЬОЇ свічки вікна — це свічка рішення.
        # Саме на її закритті ми вирішуємо, заходити чи ні, і саме з неї
        # оракул рахував вхід.
        h_last = x[:, -1, :]
        h_last = self.gelu(self.fc(h_last))

        return h_last, feature_weights

    #------------------------------
    # Голови: перетворюють стан на відповіді
    #------------------------------

    def predict_heads(self, h_last: torch.Tensor, port_state: torch.Tensor = None):
        """
        :param h_last: вектор свічки рішення [Батч, d_model]
        :param port_state: 5 чисел про стан рахунку. Поки завжди нулі — це заготовка
                           під баланс, відкриті позиції, просідання тощо.
        :return: logits [Батч, Горизонтів, 3], tp [Батч, Горизонтів],
                 sl [Батч, Горизонтів], value [Батч, 1]
        """
        if port_state is None:
            port_state = torch.zeros(h_last.size(0), 5, device=h_last.device)

        combined = torch.cat([h_last, port_state], dim=-1)

        # Кожна голова відповідає за свій горизонт. stack складає їх у один тензор.
        # logits — це «сирі бали» по трьох класах; у ймовірності їх перетворює
        # softmax уже у функції втрат.
        logits = torch.stack([head(combined) for head in self.direction_heads], dim=1)

        # Тейк і стоп проходять через softplus — плавний аналог «не менше нуля».
        # Від'ємна ціль угоди неможлива за побудовою. Раніше голова спокійно видавала
        # мінус, а симулятор ховав це під модулем, і поламаний вихід виглядав
        # у звіті правдоподібно.
        tp_pred = F.softplus(torch.cat([head(combined) for head in self.tp_heads], dim=-1))
        sl_pred = F.softplus(torch.cat([head(combined) for head in self.sl_heads], dim=-1))

        value_pred = self.value_head(combined)

        return logits, tp_pred, sl_pred, value_pred

    #------------------------------
    # forward: повний прохід
    #------------------------------

    def forward(self, x: torch.Tensor, port_state: torch.Tensor = None):
        """
        Головний метод. Його викликає навчання й бенчмарк.
        :param x: вікно свічок [Батч, Свічки, Фічі]
        :param port_state: стан рахунку (поки нулі)
        :return: logits, tp, sl, value, ваги фічей
        """
        h_last, feature_weights = self.encode(x)
        logits, tp_pred, sl_pred, value_pred = self.predict_heads(h_last, port_state)
        return logits, tp_pred, sl_pred, value_pred, feature_weights


